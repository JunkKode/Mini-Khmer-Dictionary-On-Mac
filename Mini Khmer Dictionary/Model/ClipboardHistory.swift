import AppKit
import Combine
import CryptoKit
import ImageIO

/// One thing that was copied.
nonisolated struct ClipboardItem: Identifiable, Codable, Sendable {
    enum Kind: String, Codable, Sendable { case text, image, files }

    let id: UUID
    var kind: Kind
    /// The text, or for files their names, one per line.
    var text: String
    /// Formatting kept beside the text, in `<id>.rtf`.
    var hasRichText = false
    /// Pasteboard type of the image kept in `<id>.image`.
    var imageType: String?
    var imageWidth: Int?
    var imageHeight: Int?
    /// File URLs, for files copied in Finder.
    var files: [String] = []
    /// Identifies the content, so copying the same thing again moves it up
    /// instead of adding it twice.
    var digest: String
    var date: Date
    var sourceName: String?
    var sourceBundleID: String?
    var isPinned = false
    var isFavorite = false
}

/// What's been copied while the app runs, newest first, kept across
/// launches. The pasteboard has no change notification, so it is polled.
@MainActor
final class ClipboardHistory: ObservableObject {
    static let shared = ClipboardHistory()

    /// Items kept besides pinned and favorite ones, which are never dropped.
    static let limit = 60
    private static let enabledKey = "clipboardHistoryEnabled"
    private static let maximumTextLength = 500_000
    private static let maximumImageBytes = 25_000_000
    /// Marked by password managers and similar apps: never recorded.
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "com.apple.is-remote-clipboard",
    ]

    @Published private(set) var items: [ClipboardItem] = []
    @Published var isEnabled: Bool = UserDefaults.standard.object(forKey: ClipboardHistory.enabledKey) as? Bool ?? true {
        didSet {
            UserDefaults.standard.set(isEnabled, forKey: Self.enabledKey)
            lastChangeCount = NSPasteboard.general.changeCount
        }
    }

    /// Whether the popup stays open after pasting, for pasting several
    /// items in a row. Set by the shortcut that opens the popup (⇧⌘V off,
    /// ⇧⌘X on) and switched with the pin button or ⌘D.
    @Published var keepsPopupOpen = false
    
    private var timer: Timer?
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var pauseCount = 0
    private var saveTask: Task<Void, Never>?
    private let thumbnails = NSCache<NSString, NSImage>()
    private let directory: URL = {
        let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        return base.appendingPathComponent("ClipboardHistory", isDirectory: true)
    }()

    private init() {}

    /// Loads the saved history and starts watching the pasteboard.
    func start() {
        guard timer == nil else { return }
        load()
        lastChangeCount = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    /// Stops recording, for copies the app makes on the user's behalf (the
    /// ⌥Space look-up reads the selection through the pasteboard).
    func pause() {
        pauseCount += 1
    }

    /// Starts recording again, skipping whatever changed while paused.
    func resume() {
        pauseCount = max(0, pauseCount - 1)
        lastChangeCount = NSPasteboard.general.changeCount
    }

    /// Pinned items first, in the order they were pinned, then the rest,
    /// newest first.
    var ordered: [ClipboardItem] {
        items.filter(\.isPinned) + items.filter { !$0.isPinned }
    }

    // MARK: - Recording

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        guard isEnabled, pauseCount == 0 else { return }
        capture(pasteboard)
    }

    private func capture(_ pasteboard: NSPasteboard) {
        let types = pasteboard.types ?? []
        guard !types.contains(where: { Self.ignoredTypes.contains($0.rawValue) }) else { return }

        let source = NSWorkspace.shared.frontmostApplication
        var item = ClipboardItem(
            id: UUID(), kind: .text, text: "", digest: "", date: Date(),
            sourceName: source?.localizedName, sourceBundleID: source?.bundleIdentifier
        )
        var rtf: Data?
        var image: Data?

        let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL] ?? []
        if !urls.isEmpty {
            item.kind = .files
            item.files = urls.map(\.absoluteString)
            item.text = urls.map(\.lastPathComponent).joined(separator: "\n")
            item.digest = Self.digest(Data(item.files.joined(separator: "\n").utf8))
        } else if let string = pasteboard.string(forType: .string),
                  !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            guard string.count <= Self.maximumTextLength else { return }
            item.text = string
            item.digest = Self.digest(Data(string.utf8))
            rtf = pasteboard.data(forType: .rtf)
            item.hasRichText = rtf != nil
        } else if let type = [NSPasteboard.PasteboardType.png, .tiff].first(where: types.contains),
                  let data = pasteboard.data(forType: type), data.count <= Self.maximumImageBytes {
            item.kind = .image
            item.imageType = type.rawValue
            item.digest = Self.digest(data)
            if let source = CGImageSourceCreateWithData(data as CFData, nil),
               let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any] {
                item.imageWidth = properties[kCGImagePropertyPixelWidth] as? Int
                item.imageHeight = properties[kCGImagePropertyPixelHeight] as? Int
            }
            item.text = "Image"
            image = data
        } else {
            return
        }
        add(item, rtf: rtf, image: image)
    }

    private func add(_ new: ClipboardItem, rtf: Data?, image: Data?) {
        var item = new
        if let index = items.firstIndex(where: { $0.digest == item.digest && $0.kind == item.kind }) {
            // Copied again: keep its pin and star, and move it up.
            let old = items.remove(at: index)
            item.isPinned = old.isPinned
            item.isFavorite = old.isFavorite
            deleteFiles(of: old)
            if old.isPinned {
                items.insert(item, at: index)
            } else {
                items.insert(item, at: 0)
            }
        } else {
            items.insert(item, at: 0)
        }

        try? FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        if let rtf { try? rtf.write(to: fileURL(item, "rtf")) }
        if let image { try? image.write(to: fileURL(item, "image")) }

        trim()
        scheduleSave()
    }

    private func trim() {
        var kept = 0
        for item in items where !item.isPinned && !item.isFavorite {
            kept += 1
            if kept > Self.limit { remove(item) }
        }
    }

    // MARK: - Editing

    func togglePin(_ item: ClipboardItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].isPinned.toggle()
        // Newly pinned items go below those pinned before them.
        if items[index].isPinned {
            let pinned = items.remove(at: index)
            let lastPinned = items.lastIndex(where: \.isPinned).map { $0 + 1 } ?? 0
            items.insert(pinned, at: lastPinned)
        }
        scheduleSave()
    }

    func toggleFavorite(_ item: ClipboardItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].isFavorite.toggle()
        trim()
        scheduleSave()
    }

    func remove(_ item: ClipboardItem) {
        items.removeAll { $0.id == item.id }
        deleteFiles(of: item)
        scheduleSave()
    }

    /// Removes everything except pinned and favorite items.
    func clear() {
        for item in items where !item.isPinned && !item.isFavorite {
            remove(item)
        }
    }

    // MARK: - Pasting

    /// Puts `item` back on the pasteboard. With `plainText`, text goes
    /// without its formatting. With `moveToTop`, the item becomes the newest;
    /// a kept-open popup leaves the list as it is, so items don't jump while
    /// the user works down it.
    func write(_ item: ClipboardItem, plainText: Bool = false, moveToTop: Bool = true) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch item.kind {
            case .text:
                let entry = NSPasteboardItem()
                entry.setString(item.text, forType: .string)
                if !plainText, item.hasRichText, let rtf = try? Data(contentsOf: fileURL(item, "rtf")) {
                    entry.setData(rtf, forType: .rtf)
                }
                pasteboard.writeObjects([entry])
            case .image:
                guard let type = item.imageType, let data = try? Data(contentsOf: fileURL(item, "image")) else { return }
                pasteboard.setData(data, forType: NSPasteboard.PasteboardType(type))
            case .files:
                let urls = item.files.compactMap(URL.init(string:))
                pasteboard.writeObjects(urls as [NSURL])
        }
        // Not a new copy: move the item up without recording it again (which
        // would credit it to whichever app is in front).
        lastChangeCount = pasteboard.changeCount
        if moveToTop, let index = items.firstIndex(where: { $0.id == item.id }), !items[index].isPinned {
            var used = items.remove(at: index)
            used.date = Date()
            items.insert(used, at: items.firstIndex { !$0.isPinned } ?? items.count)
            scheduleSave()
        }
    }

    // MARK: - Previews

    /// A small version of a copied image, for the list.
    func thumbnail(for item: ClipboardItem) -> NSImage? {
        guard item.kind == .image else { return nil }
        let key = item.id.uuidString as NSString
        if let cached = thumbnails.object(forKey: key) { return cached }
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceThumbnailMaxPixelSize: 320,
            kCGImageSourceCreateThumbnailWithTransform: true,
        ]
        guard let source = CGImageSourceCreateWithURL(fileURL(item, "image") as CFURL, nil),
              let cgImage = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary) else { return nil }
        let image = NSImage(cgImage: cgImage, size: NSSize(width: cgImage.width, height: cgImage.height))
        thumbnails.setObject(image, forKey: key)
        return image
    }

    // MARK: - Storage

    private var indexURL: URL { directory.appendingPathComponent("history.json") }

    private func fileURL(_ item: ClipboardItem, _ suffix: String) -> URL {
        directory.appendingPathComponent("\(item.id.uuidString).\(suffix)")
    }

    private func deleteFiles(of item: ClipboardItem) {
        try? FileManager.default.removeItem(at: fileURL(item, "rtf"))
        try? FileManager.default.removeItem(at: fileURL(item, "image"))
        thumbnails.removeObject(forKey: item.id.uuidString as NSString)
    }

    private func load() {
        guard let data = try? Data(contentsOf: indexURL),
              let saved = try? JSONDecoder().decode([ClipboardItem].self, from: data) else { return }
        items = saved
    }

    private func scheduleSave() {
        saveTask?.cancel()
        let snapshot = items
        let url = indexURL
        let directory = directory
        saveTask = Task.detached(priority: .utility) {
            try? await Task.sleep(for: .milliseconds(300))
            guard !Task.isCancelled else { return }
            try? FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
            if let data = try? JSONEncoder().encode(snapshot) {
                try? data.write(to: url, options: .atomic)
            }
        }
    }

    private static func digest(_ data: Data) -> String {
        SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }
}
